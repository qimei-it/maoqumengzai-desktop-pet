import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceIndex = process.argv.indexOf('--source')
const source =
  sourceIndex >= 0
    ? resolve(process.argv[sourceIndex + 1] || '')
    : resolve(
        root,
        '../../wechat-miniprogram/maoquyinghua/maoquyinghua-frontend/src/styles/tokens.css',
      )
const original = await readFile(source, 'utf8')
if (!/^page\s*\{/m.test(original) || /@import|url\s*\(/i.test(original))
  throw new Error('Unexpected design-token source; inspect before syncing.')
const sha256 = createHash('sha256').update(original).digest('hex')
const css = original
  .replace(/^page\s*\{/m, ':root {')
  .replace(/(-?\d*\.?\d+)rpx\b/g, (_, value) => `${Number(value) / 2}px`)
await mkdir(resolve(root, 'src/renderer/styles'), { recursive: true })
await mkdir(resolve(root, 'docs/design'), { recursive: true })
await writeFile(
  resolve(root, 'src/renderer/styles/tokens.css'),
  `/* Generated by npm run sync:design from Maoquyinghua frontend.
 * Source SHA-256: ${sha256}
 * rpx -> desktop CSS px at 375px mobile reference width (1 rpx = 0.5px).
 * Update the canonical source and re-sync; desktop adaptations live in patterns.css.
 */\n${css}`,
)
await writeFile(
  resolve(root, 'docs/design/source.json'),
  JSON.stringify(
    {
      sourceRepository: 'maoquyinghua-frontend',
      sourceFile: 'src/styles/tokens.css',
      relatedFiles: ['src/styles/patterns.css', 'docs/design/tokens.md'],
      sourceSha256: sha256,
      sourceRelativeToProject: relative(root, source),
      adaptations: [
        'page selector becomes :root',
        'rpx values become px at 0.5 scale',
      ],
    },
    null,
    2,
  ) + '\n',
)
console.log(
  'Synced canonical palette, typography, spacing, materials and three themes. Source SHA-256:',
  sha256,
)
